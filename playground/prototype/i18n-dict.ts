/**
 * 句式:带数字 / 名称的整句。第二项是替换串或 replace 回调。
 * tc = 递归翻译「一段中文」的函数(i18n.ts 传入 translateCore),「搜索 xxx」「请输入 xxx」这类要把后半段再查一遍词典。
 */
export function makeRx(tc: (s: string) => string): RxPair[] {
  return [
    [/共 ([\d,]+) 条/g, 'Total $1'],
    [/(\d+) \/ 页/g, '$1 / page'],
    [/已选 (\d+) 项/g, '$1 selected'],
    [/(\d+) 天前/g, '$1 days ago'],
    [/确定删除所选 (\d+) 项吗\?/g, 'Delete the $1 selected items?'],
    [/确认删除所选 (\d+) 项\?/g, 'Delete the $1 selected items?'],
    [/已删除 (\d+) 项/g, 'Deleted $1 item(s)'],
    [/已删除 (\S+)/g, 'Deleted $1'],
    [/已审核 (\d+) 项/g, 'Approved $1 item(s)'],
    [/所选 (\d+) 项无需审核/g, 'The $1 selected need no approval'],
    [/已导出所选 (\d+) 项/g, 'Exported $1 selected item(s)'],
    [/已导出 (\d+) 条/g, 'Exported $1 rows'],
    [/已导入 (.+):(\d+) 条/g, 'Imported $1: $2 rows'],
    [
      /请求失败\(400\):日期范围过大,请缩小到 1 年以内/g,
      'Request failed (400): date range too large, keep it within 1 year',
    ],
    [/物料编码 (\S+) 已存在/g, 'Material code $1 already exists'],
    [/条件 (\d+)/g, 'Condition $1'],
    [/搜索 (.+)/g, (_m: string, a: string) => 'Search ' + tc(a)],
    [/请输入(.{2,})/g, (_m: string, a: string) => 'Please enter ' + tc(a)],
    [/请选择(.{2,})/g, (_m: string, a: string) => 'Please select ' + tc(a)],
    [/确认删除所选 (\d+) 项/g, 'Delete the $1 selected items?'],
    [/所选 (\d+) 项/g, '$1 selected'],
    [/(\d+) 项/g, '$1 item(s)'],
    [/第 (\d+) 页/g, 'Page $1'],
    [/共 (\d+) 项/g, '$1 items'],
    [/(\d+) 行/g, '$1 rows'],
    [/\(已筛选 (\d+) 条\)/g, ' ($1 active)'],
  ]
}
